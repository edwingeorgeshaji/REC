// Ongoing first; completed roles by end month, with newest starts breaking ties.
// ISO YYYY-MM values keep sorting independent of display wording.
export const experience = experienceRecords.toSorted((a,b)=>{
  const left=a.roles[0],right=b.roles[0];
  return Number(right.current)-Number(left.current)
    || (right.current?right.start||'':right.end||'').localeCompare(left.current?left.start||'':left.end||'')
    || (right.start||'').localeCompare(left.start||'');
});
